export const rnd = (rng, a) => a[Math.floor(rng.next() * a.length)];

export const person = (rng) => ({
  name: `${rnd(rng, rng.chance(0.5) ? FIRST_M : FIRST_F)} ${rnd(rng, LAST)}`,
  loyalty: rng.range(0.35, 0.95),
  competence: rng.range(0.25, 0.95),
  corruption: rng.range(0, 0.7),
});

